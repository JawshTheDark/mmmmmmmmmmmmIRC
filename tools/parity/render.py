"""Render docs/PARITY.md from the TSV files in tools/parity/data/.

Parity is measured against everything mIRC documents. The only exclusions are
rows marked `not-possible` (Windows-only technology), each with a reason:

    parity % = (done + substitute) / (total - not-possible - n/a)

Within a category, `planned` rows are listed by corpus usage (most used by real
scripts first) so the list doubles as the order of work.

Usage: render.py            # writes docs/PARITY.md
       render.py --check    # exit 1 on malformed rows (for CI)
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
OUT = os.path.join(HERE, "..", "..", "docs", "PARITY.md")
STATUSES = ("planned", "partial", "done", "substitute", "not-possible", "n/a")
FILES = [("commands", "Commands"), ("identifiers", "Identifiers"), ("events", "Events"),
         ("syntax", "Language syntax"), ("features", "Features, options and UI")]


def read(name):
    with open(os.path.join(DATA, name + ".tsv"), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def pct(rows):
    counted = [r for r in rows if r["status"] not in ("not-possible", "n/a")]
    done = [r for r in counted if r["status"] in ("done", "substitute")]
    return (100.0 * len(done) / len(counted)) if counted else 0.0, len(done), len(counted)


def main():
    check = "--check" in sys.argv
    bad = 0
    sections = []
    summary = ["| Category | Done | Counted | Parity | not-possible |", "|---|---:|---:|---:|---:|"]
    totals = {"done": 0, "counted": 0}
    for fname, title in FILES:
        rows = read(fname)
        for r in rows:
            if r["status"] not in STATUSES:
                print(f"{fname}.tsv: {r['name']}: bad status {r['status']!r}", file=sys.stderr)
                bad += 1
        p, done, counted = pct(rows)
        np_ = sum(1 for r in rows if r["status"] == "not-possible")
        totals["done"] += done
        totals["counted"] += counted
        summary.append(f"| {title} | {done} | {counted} | {p:.1f}% | {np_} |")

        by_status = {s: [r for r in rows if r["status"] == s] for s in STATUSES}
        lines = [f"## {title}", ""]
        for s in STATUSES:
            group = by_status[s]
            if not group:
                continue
            if s == "planned":
                group = sorted(group, key=lambda r: (-int(r.get("corpus_uses") or 0), r["name"].lower()))
            lines.append(f"### {s} ({len(group)})")
            lines.append("")
            if fname == "features":
                lines.append("| Item | Group | Since | Test | Notes |")
                lines.append("|---|---|---|---|---|")
                for r in group:
                    lines.append(f"| {r['name']} | {r.get('group','')} | {r.get('since','')} | {r.get('test','')} | {r.get('notes','')} |")
            else:
                lines.append("| Item | Uses in corpus | Since | Help page | Test | Notes |")
                lines.append("|---|---:|---|---|---|---|")
                for r in group:
                    lines.append(f"| `{r['name']}` | {r.get('corpus_uses','')} | {r.get('since','')} | {r.get('help_page','')} | {r.get('test','')} | {r.get('notes','')} |")
            lines.append("")
        sections.append("\n".join(lines))

    overall = 100.0 * totals["done"] / totals["counted"] if totals["counted"] else 0.0
    summary.append(f"| **Total** | **{totals['done']}** | **{totals['counted']}** | **{overall:.1f}%** | |")
    if check:
        return 1 if bad else 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("# mIRC parity matrix\n\n")
        f.write("Generated by `tools/parity/render.py` from `tools/parity/data/*.tsv`; edit the TSVs, not this file.\n\n")
        f.write("Statuses: `planned` (not started), `partial`, `done`, `substitute` (works, Linux equivalent), "
                "`not-possible` (Windows-only technology, reason in notes), `n/a` (does not apply). "
                "Parity counts done + substitute over everything except not-possible and n/a. "
                "`planned` rows are ordered by how often the reference script corpus uses them.\n\n")
        f.write("\n".join(summary) + "\n\n")
        f.write("\n".join(sections))
    print("\n".join(summary))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
